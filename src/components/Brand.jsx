export function Logo({ variant = 'brand', height = 36, style }) {
  const tone = TONES[variant] ?? TONES.brand;
  return (
    <svg
      viewBox={LOCKUP_VIEWBOX}
      height={height}
      width={height * LOCKUP_RATIO}
      role="img"
      aria-label="MaratonArq"
      style={{ display: 'block', ...style }}
    >
      <MarkShapes {...tone} />
      {WORDMARK.map((d) => <path key={d.slice(0, 12)} fill={tone.dark} d={d} />)}
    </svg>
  );
}

// `fluid` faz o símbolo acompanhar a largura do contêiner (o viewBox mantém a
// proporção); sem ele, `size` é a largura em px.
export function LogoMark({ variant = 'white', size = 120, fluid = false, style }) {
  const tone = TONES[variant] ?? TONES.white;
  const dims = fluid
    ? { style: { display: 'block', width: '100%', height: 'auto', ...style } }
    : { width: size, height: size / MARK_RATIO, style: { display: 'block', ...style } };

  return (
    <svg viewBox={MARK_VIEWBOX} aria-hidden="true" {...dims}>
      <MarkShapes {...tone} />
    </svg>
  );
}

